"""Workflow states (System Design 3.4) and the only permitted transitions."""
from __future__ import annotations

from enum import Enum


class WS(str, Enum):
    CREATED = "CREATED"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    INTENT_PARSED = "INTENT_PARSED"
    DISCOVERING = "DISCOVERING"
    EVALUATING = "EVALUATING"
    EVIDENCE_INCOMPLETE = "EVIDENCE_INCOMPLETE"
    CONTRACT_CREATED = "CONTRACT_CREATED"
    CHECKOUT_VERIFICATION = "CHECKOUT_VERIFICATION"
    CHECKOUT_BLOCKED = "CHECKOUT_BLOCKED"
    PAYMENT_PENDING_APPROVAL = "PAYMENT_PENDING_APPROVAL"
    PAYMENT_CAPTURED = "PAYMENT_CAPTURED"
    PAYMENT_FAILED = "PAYMENT_FAILED"
    RECONCILIATION = "RECONCILIATION"
    RECONCILIATION_REQUIRED = "RECONCILIATION_REQUIRED"
    PASSPORT_GENERATED = "PASSPORT_GENERATED"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"


_T: dict[WS, set[WS]] = {
    WS.CREATED: {WS.INTENT_PARSED, WS.NEEDS_CLARIFICATION, WS.CANCELLED},
    WS.NEEDS_CLARIFICATION: {WS.INTENT_PARSED, WS.NEEDS_CLARIFICATION, WS.CANCELLED},
    WS.INTENT_PARSED: {WS.DISCOVERING, WS.CANCELLED},
    WS.DISCOVERING: {WS.EVALUATING, WS.EVIDENCE_INCOMPLETE, WS.CANCELLED},
    WS.EVALUATING: {WS.CONTRACT_CREATED, WS.EVIDENCE_INCOMPLETE, WS.CANCELLED},
    WS.EVIDENCE_INCOMPLETE: {WS.DISCOVERING, WS.CANCELLED},
    WS.CONTRACT_CREATED: {WS.CHECKOUT_VERIFICATION, WS.CONTRACT_CREATED, WS.CANCELLED, WS.EXPIRED,
                          WS.RECONCILIATION},  # RECONCILIATION: purchase reported from a real store
    WS.CHECKOUT_VERIFICATION: {WS.PAYMENT_PENDING_APPROVAL, WS.CHECKOUT_BLOCKED, WS.CANCELLED},
    WS.CHECKOUT_BLOCKED: {WS.CHECKOUT_VERIFICATION, WS.CONTRACT_CREATED, WS.CANCELLED, WS.EXPIRED},
    WS.PAYMENT_PENDING_APPROVAL: {WS.PAYMENT_CAPTURED, WS.PAYMENT_FAILED, WS.CHECKOUT_VERIFICATION,
                                  WS.CONTRACT_CREATED, WS.CANCELLED, WS.EXPIRED},
    WS.PAYMENT_FAILED: {WS.PAYMENT_PENDING_APPROVAL, WS.PAYMENT_CAPTURED, WS.CHECKOUT_VERIFICATION,
                        WS.CONTRACT_CREATED, WS.CANCELLED},
    WS.PAYMENT_CAPTURED: {WS.RECONCILIATION},
    WS.RECONCILIATION: {WS.PASSPORT_GENERATED, WS.RECONCILIATION_REQUIRED},
    WS.RECONCILIATION_REQUIRED: {WS.PASSPORT_GENERATED},
    WS.PASSPORT_GENERATED: {WS.COMPLETED},
    WS.COMPLETED: set(),
    WS.CANCELLED: set(),
    WS.EXPIRED: set(),
}

TERMINAL = {WS.COMPLETED, WS.CANCELLED, WS.EXPIRED}
POST_CAPTURE = {WS.PAYMENT_CAPTURED, WS.RECONCILIATION, WS.RECONCILIATION_REQUIRED, WS.PASSPORT_GENERATED,
                WS.COMPLETED}
AUTOMATIC = {WS.CREATED, WS.INTENT_PARSED, WS.DISCOVERING, WS.EVALUATING}


class InvalidTransition(RuntimeError):
    pass


def can_transition(src: str, dst: str) -> bool:
    return WS(dst) in _T[WS(src)]


def assert_transition(src: str, dst: str) -> None:
    if not can_transition(src, dst):
        raise InvalidTransition(f"Invalid workflow transition {src} -> {dst}")
